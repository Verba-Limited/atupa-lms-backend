import { Body, Controller, Delete, Get, Post } from '@nestjs/common';
import { ApiBearerAuth, ApiProperty, ApiTags } from '@nestjs/swagger';
import { Throttle } from '@nestjs/throttler';
import { IsString, Length } from 'class-validator';
import type { Actor } from '../../../../shared/application/actor';
import { UserRole } from '../../../../shared/domain/user-role';
import { CurrentUser } from '../../../../shared/presentation/decorators/current-user.decorator';
import { Roles } from '../../../../shared/presentation/decorators/roles.decorator';
import { ok } from '../../../../shared/presentation/http/api-response';
import { IdParam } from '../../../../shared/presentation/http/id-param';
import { ParentsService } from '../../application/parents.service';

export class LinkChildDto {
  @ApiProperty({
    example: 'K7M2Q9XD',
    description: 'Code generated by the learner',
  })
  @IsString()
  @Length(8, 8)
  code!: string;
}

@ApiTags('Parents')
@ApiBearerAuth()
@Controller('parents')
export class ParentsController {
  constructor(private readonly parents: ParentsService) {}

  /** Learner: create a code for a parent to link to this account (30 min). */
  @Roles(UserRole.LEARNER)
  @Post('link-codes')
  async createLinkCode(@CurrentUser() actor: Actor) {
    return ok(
      await this.parents.createLinkCode(actor),
      'Share this code with your parent',
    );
  }

  @Roles(UserRole.PARENT)
  @Throttle({ default: { limit: 10, ttl: 60_000 } })
  @Post('children')
  async linkChild(@CurrentUser() actor: Actor, @Body() dto: LinkChildDto) {
    return ok(await this.parents.linkWithCode(actor, dto.code), 'Child linked');
  }

  @Roles(UserRole.PARENT)
  @Get('children')
  async children(@CurrentUser() actor: Actor) {
    return ok(await this.parents.listChildren(actor.userId));
  }

  @Roles(UserRole.PARENT)
  @Delete('children/:childId')
  async unlink(
    @CurrentUser() actor: Actor,
    @IdParam('childId') childId: string,
  ) {
    await this.parents.unlink(actor, childId);
    return ok(null, 'Child unlinked');
  }
}
